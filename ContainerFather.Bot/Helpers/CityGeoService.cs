    // Список стран и регионов (не города)
    private static readonly HashSet<string> NonCityEntries = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
    {
        "Китай", "Узбекистан", "СНГ", "Россия", "РФ", "Беларусь", "Казахстан"
    };

    /// <summary>
    /// Получить координаты одного города
    /// </summary>
    public static CityCoordinates GetCityCoordinatesAsync(string city)
    {
        var result = new CityCoordinates { City = city };

        // Сначала проверяем локальную базу
        if (LocalCityDatabase.TryGetValue(city, out var coords))
        {
            result.Latitude = coords.Lat;
            result.Longitude = coords.Lon;
            result.IsFound = true;
            return result;
        }

        return result;
    }

    /// <summary>
    /// Получить уникальные города из списка
    /// </summary>
    public static List<string> GetUniqueCities(List<string> cities)
    {
        return cities
            .Where(c => !string.IsNullOrWhiteSpace(c))
            .Select(c => c.Trim())
            .Where(c => !NonCityEntries.Contains(c))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(c => c)
            .ToList();
    }
